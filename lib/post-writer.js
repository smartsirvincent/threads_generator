  const v = variationSpec(variant);
  const seriesLine = seriesTotal > 1 ? `這是同主題系列的第 ${seriesIndex}/${seriesTotal} 篇,務必和系列其他篇「完全不同款」:不同開場、不同例子、不同句子節奏、不同結尾 CTA,不要重複相同的賣點措辭。\n` : '';
  const variantBlock = `**這一篇的差異化設定(務必嚴格遵守,整篇都要體現)**:
${seriesLine}- 敘事視角:${v.pov}
- 開場方式:${v.hook}(第一句就要用這個方式,且不要和其他篇雷同)
- 內容焦點:${v.focus}(整篇圍繞這個切角發揮,不要面面俱到)
- 語氣風味:${v.tone}
- 篇章結構:${v.struct}
- 內容手法:${v.move}
- 具體情境:${v.anchor}
※以上設定都必須繞著【主題:${topicName}】發揮,主角療程只能是「${topicName}」,不可換成或舉例成其他療程(如皮秒、電波等)。`;
