const pick = (arr, i, stride, off = 0) => arr[((i * stride + off) % arr.length + arr.length) % arr.length];

// 各軸步長「與該軸長度互質」→ variant 遞增時每軸都能輪完全部值,且彼此不同步,組合最大化
function variationSpec(variant) {
  const i = Math.max(0, variant | 0);
  return {
    pov: pick(POV, i, 1, 0),      // len6, stride1(互質)
    hook: pick(HOOK, i, 5, 1),    // len6, stride5(互質)
    focus: pick(FOCUS, i, 2, 0),  // len7, stride2(互質)
    tone: pick(TONE, i, 2, 2),    // len5, stride2(互質)
    struct: pick(STRUCT, i, 3, 1),// len5, stride3(互質)
    move: pick(MOVE, i, 5, 2),    // len6, stride5(互質)
    anchor: pick(ANCHOR, i, 3, 3),// len7, stride3(互質)
  };
}

// Threads 是純文字平台:清掉 markdown 粗體/標題等符號(hashtag #tag 保留)
export function sanitizeText(t) {
  let s = String(t || '');
  s = s.replace(/\*\*(.*?)\*\*/gs, '$1').replace(/\*\*/g, '');   // **粗體**
  s = s.replace(/__(.*?)__/gs, '$1').replace(/__/g, '');          // __底線__
  s = s.replace(/`{1,3}/g, '');                                   // 反引號
  s = s.replace(/^\s{0,3}#{1,6}\s+/gm, '');                       // # markdown 標題(hashtag 無空格,不受影響)
  s = s.replace(/^\s{0,3}>\s?/gm, '');                            // > 引用
  s = s.replace(/^\s{0,3}\*\s+/gm, '・');                          // * 項目符號 → ・
  return s.trim();
}

